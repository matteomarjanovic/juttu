		<h1>Privacy Policy</h1>
		<p class="text-sm text-base-content/60">Last updated: March 2026</p>

		<h2>What Juttu is</h2>
		<p>
			Juttu is a comment widget that website owners embed in their sites. Comments are stored on the
			Bluesky / AT Protocol network, not on Juttu's servers.
		</p>

		<h2>Handle resolution and Bluesky</h2>
		<p>
			When you log in with the <strong>Login with Bluesky</strong> button, Juttu uses
			<strong>bsky.social</strong> to resolve your handle and start the OAuth flow. This means your
			<strong>IP address and Bluesky handle are sent to Bluesky (bsky.social)</strong> as part of that
			request.
		</p>
		<p>
			If you log in with a handle on a <strong>custom PDS</strong> (Personal Data Server), handle
			resolution goes to that PDS instead of bsky.social.
		</p>
		<p>
			Bluesky's own privacy practices are described in their <a
				href="https://bsky.social/about/support/privacy-policy"
				target="_blank"
				rel="noopener noreferrer">Privacy Policy</a
			>.
		</p>

		<h2>What Juttu stores</h2>
		<p>
			Juttu does not store personal data on its servers beyond what is required to maintain your
			OAuth session (an encrypted session token). No comment content, profile information, or
			browsing history is stored by Juttu.
		</p>
		<p>
			All comments you post are published to the Bluesky network and are subject to Bluesky's terms
			and privacy policy.
		</p>

		<h2>Analytics</h2>
		<p>
			Juttu collects minimal, anonymous usage events (e.g. page views) to understand how the widget
			is used. No personally identifiable information is included in these events.
		</p>

		<h2>Contact</h2>
		<p>
			If you have questions about this policy, open an issue on the <a
				href="https://github.com/mozzius/juttu"
				target="_blank"
				rel="noopener noreferrer">Juttu GitHub repository</a
			>.
		</p>
